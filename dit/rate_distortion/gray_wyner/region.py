"""
Coordinate systems on the Gray-Wyner region.

The Gray-Wyner rate region, the *region of tension* of Prabhakaran &
Prabhakaran :cite:`prabhakaran2014assisted`, the *extension profile* of
Matveev & Romashchenko :cite:`matveev2026beyond`, and the *mutual information
region* of Li & El Gamal :cite:`li2018extended` are all images of one another
under invertible affine maps. Every one of them is generated by the same
auxiliary variable ``W``; they differ only in which affine functions of the
entropies of ``(X_0, ..., X_{n-1}, W)`` are recorded.

Writing ``R_0 = I[X_{0:n} : W]`` and ``R_i = H[X_i | W]`` for the Gray-Wyner
rates, the maps are

.. math::

    \\tau_i     &= R_0 + R_i - H[X_i]           &&= I[X_{-i} : W | X_i] \\\\
    \\tau_{res} &= R_0 + \\sum_i R_i - H[X_{0:n}] &&= T[X_{0:n} | W] \\\\
    v_i        &= H[X_i] - R_i                 &&= I[X_i : W] \\\\
    v_{joint}  &= R_0                          &&= I[X_{0:n} : W]

The tension identities are the chain rule ``I[X_{0:n}:W] = I[X_i:W] +
I[X_{-i}:W|X_i]`` and the definition of the conditional total correlation
``T[X_{0:n}|W] = sum_i H[X_i|W] - H[X_{0:n}|W]``. The matrix carrying
``(R_0, ..., R_n)`` to ``(tau_0, ..., tau_{n-1}, tau_res)`` is unimodular, so
nothing is lost in either direction.

At ``n = 2`` the residual coordinate is ``I[X:Y|W]`` and these reduce to the
map ``g_{X,Y}`` of :cite:`prabhakaran2014assisted` (their Theorem 5.2).

Conventions
-----------
``dit`` follows the coordinate ordering of :cite:`prabhakaran2014assisted` and
:cite:`li2018extended`: the tension coordinate indexed by ``i`` is
``I[X_{-i} : W | X_i]``, so for a pair it is ``(I[Y:W|X], I[X:W|Y],
I[X:Y|W])``. Csirmaz :cite:`csirmaz2023short` swaps the first two coordinates
and omits the increasing hull (and correspondingly uses a cardinality bound of
``|X||Y| + 3`` rather than ``+ 2``). Formulas transported between these papers
must be checked against the convention in force.

The tension region proper is the *increasing hull* of the attainable tension
points -- every point dominating an attainable one is in the region. The
routines here report attainable points on the lower boundary; the hull is
implicit.

Besides the coordinate maps, this module holds the three quantities that
:cite:`li2018extended` identify as extreme points of the mutual information
region: the maximal interaction information and the two private interaction
informations. They are the reason `GrayWynerOptimizer` accepts signed
weights.
"""

